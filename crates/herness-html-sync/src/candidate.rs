//! Private candidate storage implementing the H1 [`ArtifactPort`].
//!
//! Candidate bytes live under a host-supplied private root, never under a
//! model-chosen path. The on-disk namespace is derived from the project, host
//! job identifier, and generation; the host-issued capability token is compared
//! by digest. A read or write for another project, job, generation, or token is
//! rejected before any file is touched.
//!
//! Immutable snapshots (`source_markdown`, `existing_html`, `shared_css`) are
//! staged by the host when a generation opens. Only `candidate_html` and
//! `candidate_provenance` are writable by the agent path. Candidate HTML is
//! capped at 8 MiB and Markdown at 2 MiB; over-limit content is rejected, never
//! truncated.

use std::collections::BTreeSet;
use std::fs::{self, File, OpenOptions};
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};

use herness_core::{
    ArtifactFailure, ArtifactHandle, ArtifactPort, ArtifactSlot, ArtifactSnapshot, FileVersion,
    MAX_CANDIDATE_ARTIFACT_BYTES, hash_bytes,
};
use herness_supervision::ContentDigest;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::document::DocumentKey;
use crate::error::H3Error;
use crate::state::CandidateStorageRef;
use crate::version::{H3_FORMAT_VERSION, H3Record};

/// Maximum Markdown source bytes accepted into one candidate generation.
pub const MAX_SOURCE_MARKDOWN_BYTES: usize = 2 * 1024 * 1024;
/// Maximum candidate artifact bytes accepted by the private store.
pub const MAX_CANDIDATE_BYTES: usize = MAX_CANDIDATE_ARTIFACT_BYTES;

const MANIFEST_FILE: &str = "manifest.json";
const SLOT_SOURCE: &str = "source.md";
const SLOT_EXISTING: &str = "existing.html";
const SLOT_CSS: &str = "shared.css";
const SLOT_CANDIDATE: &str = "candidate.html";
const SLOT_PROVENANCE: &str = "provenance.json";

/// Host-only request to open one candidate generation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CandidateGenerationRequest {
    document: DocumentKey,
    job_id: String,
    generation: u64,
    token: Option<String>,
    source_markdown: String,
    existing_html: Option<String>,
    shared_css: Option<String>,
}

impl CandidateGenerationRequest {
    /// Creates a generation request with validated identifiers and exact
    /// snapshots. An absent token is generated by the store.
    pub fn new(
        document: DocumentKey,
        job_id: impl AsRef<str>,
        generation: u64,
        token: Option<String>,
        source_markdown: impl Into<String>,
        existing_html: Option<String>,
        shared_css: Option<String>,
    ) -> Result<Self, H3Error> {
        if generation == 0 {
            return Err(H3Error::must_be_positive("generation"));
        }
        let job_id = job_id.as_ref().trim();
        if job_id.is_empty() {
            return Err(H3Error::empty("jobId"));
        }
        if job_id.chars().any(char::is_control) {
            return Err(H3Error::invalid("jobId", "control characters are not allowed"));
        }
        if let Some(token) = &token
            && (token.trim().is_empty() || token.chars().any(char::is_control))
        {
            return Err(H3Error::invalid(
                "artifactToken",
                "the capability token must be non-empty without control characters",
            ));
        }
        let source_markdown = source_markdown.into();
        if source_markdown.len() > MAX_SOURCE_MARKDOWN_BYTES {
            return Err(H3Error::invalid(
                "sourceMarkdown",
                format!(
                    "the Markdown source exceeds the {MAX_SOURCE_MARKDOWN_BYTES} byte limit"
                ),
            ));
        }
        Ok(Self {
            document,
            job_id: job_id.to_owned(),
            generation,
            token,
            source_markdown,
            existing_html,
            shared_css,
        })
    }

    /// Document this generation belongs to.
    pub const fn document(&self) -> &DocumentKey {
        &self.document
    }

    /// Host job identifier.
    pub fn job_id(&self) -> &str {
        &self.job_id
    }

    /// Generation number.
    pub const fn generation(&self) -> u64 {
        self.generation
    }
}

/// Host-only result of opening a candidate generation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpenedCandidateGeneration {
    handle: ArtifactHandle,
    document: DocumentKey,
    storage: CandidateStorageRef,
}

impl OpenedCandidateGeneration {
    /// Host-issued handle for H1 candidate tools.
    pub const fn handle(&self) -> &ArtifactHandle {
        &self.handle
    }

    /// Document this generation belongs to.
    pub const fn document(&self) -> &DocumentKey {
        &self.document
    }

    /// Opaque private storage reference persisted in H3 state.
    pub const fn storage(&self) -> &CandidateStorageRef {
        &self.storage
    }
}

/// A private, generation-scoped candidate artifact store.
#[derive(Debug, Clone)]
pub struct CandidateArtifactStore {
    root: PathBuf,
}
impl CandidateArtifactStore {
    /// Creates a store under an absolute private root outside the project.
    pub fn new(root: impl Into<PathBuf>) -> Result<Self, H3Error> {
        let root = root.into();
        if root.as_os_str().is_empty() {
            return Err(H3Error::empty("candidateRoot"));
        }
        if !root.is_absolute() {
            return Err(H3Error::invalid(
                "candidateRoot",
                "the private candidate root must be absolute",
            ));
        }
        if root
            .components()
            .any(|component| matches!(component, std::path::Component::ParentDir))
        {
            return Err(H3Error::invalid(
                "candidateRoot",
                "the private candidate root must not contain '..'",
            ));
        }
        Ok(Self { root })
    }

    /// Private root supplied by the host.
    pub fn root(&self) -> &Path {
        &self.root
    }

    /// Opens or idempotently reopens one generation and returns its handle.
    ///
    /// This is a host-only call. It is not a tool and has no IPC surface.
    pub fn open_generation(
        &self,
        request: CandidateGenerationRequest,
    ) -> Result<OpenedCandidateGeneration, H3Error> {
        let token = request
            .token
            .clone()
            .unwrap_or_else(|| Uuid::new_v4().to_string());
        let token_digest = ContentDigest::sha256(token.as_bytes());
        let namespace = candidate_namespace(
            request.document.project_id(),
            &request.job_id,
            request.generation,
        );
        let handle = ArtifactHandle::new(
            request.document.project_id(),
            &request.job_id,
            request.generation,
            &token,
        )
        .map_err(|error| H3Error::invalid("artifactHandle", error.to_string()))?;
        let directory = self.generation_directory(&namespace);
        fs::create_dir_all(&directory).map_err(|error| H3Error::Storage {
            detail: format!("candidate directory: {error}"),
        })?;
        set_private_directory_permissions(&directory);

        let mut immutable = vec![ImmutableEntry {
            artifact: ArtifactSlot::SourceMarkdown,
            digest: ContentDigest::sha256(request.source_markdown.as_bytes()),
            bytes: request.source_markdown.len() as u64,
        }];
        if let Some(content) = &request.existing_html {
            immutable.push(ImmutableEntry {
                artifact: ArtifactSlot::ExistingHtml,
                digest: ContentDigest::sha256(content.as_bytes()),
                bytes: content.len() as u64,
            });
        }
        if let Some(content) = &request.shared_css {
            immutable.push(ImmutableEntry {
                artifact: ArtifactSlot::SharedCss,
                digest: ContentDigest::sha256(content.as_bytes()),
                bytes: content.len() as u64,
            });
        }
        immutable.sort_by_key(|entry| entry.artifact);

        let manifest = CandidateManifest {
            format_version: H3_FORMAT_VERSION,
            project_id: request.document.project_id(),
            document: request.document.clone(),
            job_id: request.job_id.clone(),
            generation: request.generation,
            token_digest: token_digest.clone(),
            immutable,
        };
        manifest
            .validate()
            .map_err(|error| H3Error::invalid("candidateManifest", error.to_string()))?;

        let manifest_path = directory.join(MANIFEST_FILE);
        if manifest_path.exists() {
            let bytes = fs::read(&manifest_path).map_err(|error| H3Error::Storage {
                detail: format!("candidate manifest: {error}"),
            })?;
            let existing_manifest =
                crate::version::decode_record::<CandidateManifest>(&bytes)?;
            if existing_manifest != manifest {
                return Err(H3Error::RecordConflict {
                    record: "candidate generation",
                    id: namespace,
                });
            }
            return Ok(OpenedCandidateGeneration {
                handle,
                document: request.document,
                storage: CandidateStorageRef::new(namespace, token_digest)?,
            });
        }

        write_atomic(
            &directory.join(SLOT_SOURCE),
            request.source_markdown.as_bytes(),
        )?;
        if let Some(content) = &request.existing_html {
            write_atomic(&directory.join(SLOT_EXISTING), content.as_bytes())?;
        }
        if let Some(content) = &request.shared_css {
            write_atomic(&directory.join(SLOT_CSS), content.as_bytes())?;
        }
        let manifest_bytes = crate::version::encode_record(&manifest)
            .map_err(|error| H3Error::Storage {
                detail: format!("candidate manifest: {error}"),
            })?;
        write_atomic(&manifest_path, &manifest_bytes)?;

        Ok(OpenedCandidateGeneration {
            handle,
            document: request.document,
            storage: CandidateStorageRef::new(namespace, token_digest)?,
        })
    }

    fn generation_directory(&self, namespace: &str) -> PathBuf {
        self.root.join(namespace)
    }

    fn resolve(
        &self,
        handle: &ArtifactHandle,
    ) -> Result<(PathBuf, CandidateManifest), ArtifactFailure> {
        let namespace = candidate_namespace(handle.project_id(), handle.job_id(), handle.generation());
        let directory = self.generation_directory(&namespace);
        let manifest_path = directory.join(MANIFEST_FILE);
        let bytes = match fs::read(&manifest_path) {
            Ok(bytes) => bytes,
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                return Err(ArtifactFailure::StaleHandle {
                    expected_generation: handle.generation(),
                    found_generation: handle.generation(),
                });
            }
            Err(_) => return Err(ArtifactFailure::Unavailable),
        };
        let manifest = crate::version::decode_record::<CandidateManifest>(&bytes)
            .map_err(|_| ArtifactFailure::Unavailable)?;
        if manifest.project_id != handle.project_id()
            || manifest.job_id != handle.job_id()
            || manifest.generation != handle.generation()
            || manifest.token_digest != ContentDigest::sha256(handle.token().as_bytes())
        {
            return Err(ArtifactFailure::StaleHandle {
                expected_generation: manifest.generation,
                found_generation: handle.generation(),
            });
        }
        Ok((directory, manifest))
    }

    fn immutable_entry(
        manifest: &CandidateManifest,
        slot: ArtifactSlot,
    ) -> Option<&ImmutableEntry> {
        manifest
            .immutable
            .iter()
            .find(|entry| entry.artifact == slot)
    }

    fn read_slot(
        directory: &Path,
        manifest: &CandidateManifest,
        slot: ArtifactSlot,
    ) -> Result<Option<ArtifactSnapshot>, ArtifactFailure> {
        let path = directory.join(slot_file(slot));
        let bytes = match fs::read(&path) {
            Ok(bytes) => bytes,
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                if slot.is_candidate() || Self::immutable_entry(manifest, slot).is_none() {
                    return Ok(None);
                }
                return Err(ArtifactFailure::Unavailable);
            }
            Err(_) => return Err(ArtifactFailure::Unavailable),
        };
        if !slot.is_candidate() {
            let Some(entry) = Self::immutable_entry(manifest, slot) else {
                return Err(ArtifactFailure::Unavailable);
            };
            if ContentDigest::sha256(&bytes) != entry.digest {
                return Err(ArtifactFailure::Unavailable);
            }
        }
        let content = String::from_utf8(bytes).map_err(|_| ArtifactFailure::Unavailable)?;
        Ok(Some(ArtifactSnapshot::new(
            slot,
            hash_bytes(content.as_bytes()),
            content,
        )))
    }
}

impl ArtifactPort for CandidateArtifactStore {
    fn read_artifact(
        &mut self,
        handle: &ArtifactHandle,
        artifact: ArtifactSlot,
    ) -> Result<Option<ArtifactSnapshot>, ArtifactFailure> {
        let (directory, manifest) = self.resolve(handle)?;
        Self::read_slot(&directory, &manifest, artifact)
    }

    fn write_artifact(
        &mut self,
        handle: &ArtifactHandle,
        artifact: ArtifactSlot,
        content: &str,
        expected_version: Option<&FileVersion>,
    ) -> Result<ArtifactSnapshot, ArtifactFailure> {
        if !artifact.is_candidate() {
            return Err(ArtifactFailure::NotCandidateTarget { artifact });
        }
        if content.len() > MAX_CANDIDATE_BYTES {
            return Err(ArtifactFailure::NotExecutable {
                detail: format!(
                    "candidate content exceeds the {MAX_CANDIDATE_BYTES} byte limit"
                ),
            });
        }
        let (directory, _manifest) = self.resolve(handle)?;
        let path = directory.join(slot_file(artifact));
        let current = match fs::read(&path) {
            Ok(bytes) => String::from_utf8(bytes)
                .ok()
                .map(|content| hash_bytes(content.as_bytes())),
            Err(error) if error.kind() == io::ErrorKind::NotFound => None,
            Err(_) => return Err(ArtifactFailure::Unavailable),
        };
        let matches = match (expected_version, current.as_ref()) {
            (None, None) => true,
            (Some(expected), Some(found)) => expected == found,
            _ => false,
        };
        if !matches {
            let absent = FileVersion::new("absent").expect("placeholder version");
            return Err(ArtifactFailure::VersionConflict {
                artifact,
                expected: expected_version.cloned().unwrap_or(absent.clone()),
                actual: current.unwrap_or(absent),
            });
        }
        write_atomic(&path, content.as_bytes()).map_err(|_| ArtifactFailure::Unavailable)?;
        let bytes = fs::read(&path).map_err(|_| ArtifactFailure::Unavailable)?;
        let observed = String::from_utf8(bytes).map_err(|_| ArtifactFailure::Unavailable)?;
        if observed != content {
            return Err(ArtifactFailure::ContentMismatch { artifact });
        }
        Ok(ArtifactSnapshot::new(
            artifact,
            hash_bytes(observed.as_bytes()),
            observed,
        ))
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct ImmutableEntry {
    artifact: ArtifactSlot,
    digest: ContentDigest,
    bytes: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct CandidateManifest {
    format_version: u32,
    project_id: herness_core::ProjectId,
    document: DocumentKey,
    job_id: String,
    generation: u64,
    token_digest: ContentDigest,
    immutable: Vec<ImmutableEntry>,
}

impl CandidateManifest {
    fn validate(&self) -> Result<(), H3Error> {
        if self.generation == 0 {
            return Err(H3Error::must_be_positive("generation"));
        }
        if self.job_id.trim().is_empty() {
            return Err(H3Error::empty("jobId"));
        }
        if self.document.project_id() != self.project_id {
            return Err(H3Error::CrossProject {
                id_kind: "candidate document".to_owned(),
                expected: self.project_id,
                found: self.document.project_id(),
            });
        }
        let mut seen = BTreeSet::new();
        for entry in &self.immutable {
            if entry.artifact.is_candidate() {
                return Err(H3Error::invalid(
                    "immutable",
                    "a candidate slot cannot be an immutable snapshot",
                ));
            }
            if !seen.insert(entry.artifact) {
                return Err(H3Error::invalid(
                    "immutable",
                    "immutable snapshot slots must be unique",
                ));
            }
        }
        Ok(())
    }
}

impl H3Record for CandidateManifest {
    const RECORD: &'static str = "candidate manifest";
    fn format_version(&self) -> u32 {
        self.format_version
    }
}

fn candidate_namespace(project: herness_core::ProjectId, job_id: &str, generation: u64) -> String {
    let mut hasher = Sha256::new();
    hasher.update(b"h3-candidate\0");
    hasher.update(project.to_string().as_bytes());
    hasher.update(b"\0");
    hasher.update(job_id.as_bytes());
    hasher.update(b"\0");
    hasher.update(generation.to_le_bytes());
    hex_digest(&hasher.finalize())
}

fn hex_digest(bytes: &[u8]) -> String {
    let mut hex = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        use std::fmt::Write as _;
        write!(&mut hex, "{byte:02x}").expect("writing to a String cannot fail");
    }
    hex
}

fn slot_file(slot: ArtifactSlot) -> &'static str {
    match slot {
        ArtifactSlot::SourceMarkdown => SLOT_SOURCE,
        ArtifactSlot::ExistingHtml => SLOT_EXISTING,
        ArtifactSlot::SharedCss => SLOT_CSS,
        ArtifactSlot::CandidateHtml => SLOT_CANDIDATE,
        ArtifactSlot::CandidateProvenance => SLOT_PROVENANCE,
    }
}

fn write_atomic(path: &Path, bytes: &[u8]) -> Result<(), H3Error> {
    let directory = path.parent().ok_or_else(|| H3Error::Storage {
        detail: "candidate path has no parent".to_owned(),
    })?;
    let file_name = path.file_name().and_then(|name| name.to_str()).unwrap_or("file");
    let temp = directory.join(format!(".{file_name}.{}.tmp", Uuid::new_v4()));
    let result = (|| -> io::Result<()> {
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt as _;
            options.mode(0o600);
        }
        let mut file: File = options.open(&temp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        drop(file);
        fs::rename(&temp, path)?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temp);
    }
    result.map_err(|error| H3Error::Storage {
        detail: format!("candidate write: {error}"),
    })
}

fn set_private_directory_permissions(path: &Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        let _ = fs::set_permissions(path, fs::Permissions::from_mode(0o700));
    }
    #[cfg(not(unix))]
    {
        let _ = path;
    }
}
